"""Derive 67 source tables plus two independently pinned ICU tables.
No decoder backend is invoked; G08 retires this migration generator.
"""

import argparse
import hashlib
import json
import struct
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--policy", type=Path, required=True)
parser.add_argument("--icu-tables", type=Path, required=True)
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()
raw = args.policy.read_bytes()
if hashlib.sha256(raw).hexdigest() != "634dac6dfb1034ba03bf26d437a03315c4b4d38333081ef446c655b393666bde":
    raise SystemExit("filtered native input drift")
policy = json.loads(raw)
rows = [row for row in policy["canonical_codecs"] if row.get("implementation_family") == "single_byte_table"]
if len(rows) != 69:
    raise SystemExit("single-byte family drift")
source = [
    (
        "// SPDX-License-Identifier: PSF-2.0 AND Unicode-3.0\n// Generated"
        " from 67 pinned Python3.14.7 observations and two ICU tables; se"
        "e attribution.json.\n"
    )
]
expected = []
for index, row in enumerate(rows):
    if row["canonical"] in ["hp-roman8", "koi8-t"]:
        if "decoded" in row:
            raise SystemExit("excluded source table present")
        data = (args.icu_tables / (row["canonical"] + ".single.bin")).read_bytes()
        pin = {
            "hp-roman8": "3ab1586ed736dd798be7a724be74affacff64233ac96a591366099298f470c5e",
            "koi8-t": "beda557dded134d3effaad83a426a72e87aa6372262d34622110d7e2c00c82e3",
        }[row["canonical"]]
        if hashlib.sha256(data).hexdigest() != pin:
            raise SystemExit("independent ICU table drift")
        text = "".join(map(chr, struct.unpack(">256I", data)))
    else:
        text = row["decoded"]
    if len(text) != 256 or any(0xD800 <= ord(point) <= 0xDFFF for point in text):
        raise SystemExit("invalid single-byte source mapping")
    source.append(
        f"pub static TABLE_{index}: [u32;256] = [\n"
        + "".join(
            "    " + ",".join(hex(ord(point)) for point in text[start : start + 16]) + ",\n"
            for start in range(0, 256, 16)
        )
        + "];\n"
    )
    expected.append(
        dict(canonical=row["canonical"], bytes_hex=bytes(range(256)).hex(), expected=text, aliases=row["labels"])
    )
source.append(
    "pub fn table(name:&str)->Option<&'static [u32;256]> {match name {\n"
    + "".join(f"    {json.dumps(row['canonical'])} => Some(&TABLE_{index}),\n" for index, row in enumerate(rows))
    + "    _=>None,\n}}\n"
)
labels = {}
for row in policy["canonical_codecs"]:
    for label in [row["canonical"], *row["labels"]]:
        if not label.isascii():
            raise SystemExit("unexpected nonASCII captured alias")
        normalized = "_".join("".join(c.lower() if c.isalnum() or c == "." else " " for c in label).split())
        if normalized in labels and labels[normalized] != row["canonical"]:
            raise SystemExit("alias collision")
        labels[normalized] = row["canonical"]
(args.output / "src").mkdir(parents=True, exist_ok=True)
(args.output / "tests").mkdir(exist_ok=True)
(args.output / "src/singlebyte.rs").write_text("".join(source))
(args.output / "src/aliases.rs").write_text(
    (
        "// SPDX-License-Identifier: PSF-2.0\n// Pinned standard registry "
        "names; attribution.json and LICENSE-PYTHON apply.\npub fn canonic"
        "al(label:&str)->Option<&'static str>{match label {\n"
    )
    + "".join(f"    {json.dumps(k)} => Some({json.dumps(v)}),\n" for k, v in sorted(labels.items()))
    + "    _=>None,\n}}\n"
)
# Source expectations remain immutable and are not regenerated by native derivation.
